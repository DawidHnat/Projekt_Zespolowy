"""Generate TypeScript from the single SCRUM-36 contract; never infer it from examples."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "contracts/api-design.json"
TARGET = ROOT / "frontend/src/shared/api/generated/contracts.ts"


def ts(schema):
    if "$ref" in schema:
        prefix = "#/$defs/"
        if not schema["$ref"].startswith(prefix):
            raise ValueError("Only local contract references are supported")
        return schema["$ref"][len(prefix) :]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(
            json.dumps(value, ensure_ascii=False) for value in schema["enum"]
        )
    if "anyOf" in schema:
        return " | ".join(ts(value) for value in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        required = schema.get("required", [])
        return (
            "{ "
            + " ".join(
                f"{json.dumps(name)}{'' if name in required else '?'}: {ts(value)};"
                for name, value in schema["properties"].items()
            )
            + " }"
        )
    if kind == "array":
        if "prefixItems" in schema:
            if schema.get("items") is not False:
                raise ValueError(
                    "Open-ended tuples require an explicit generator change"
                )
            return "[" + ", ".join(ts(value) for value in schema["prefixItems"]) + "]"
        return f"Array<{ts(schema['items'])}>"
    primitives = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }
    if kind not in primitives:
        raise ValueError(f"Unsupported contract shape: {kind}")
    return primitives[kind]


def render(contract):
    header = (
        "// Generated by tools/generate_api_types.py from contracts/api-design.json.\n"
    )
    header += (
        "// SCRUM-36 remains proposed-for-review; do not edit this file manually.\n\n"
    )
    definitions = "\n".join(
        f"export type {name} = {ts(schema)};"
        for name, schema in contract["$defs"].items()
    )
    operations = "\n".join(
        f"  {json.dumps(op['method'] + ' ' + op['path'])}: {ts(op['response_schema'])};"
        for op in contract["operations"]
        if op["implementation_status"] == "implemented"
    )
    return (
        header + definitions + "\n\nexport type Responses = {\n" + operations + "\n};\n"
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != content:
            raise SystemExit(
                "Generated API types are stale: run python3 tools/generate_api_types.py"
            )
        print("Generated API types match the SCRUM-36 contract")
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(content)


if __name__ == "__main__":
    main()
